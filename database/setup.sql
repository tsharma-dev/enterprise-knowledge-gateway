-- Run as a PostgreSQL administrator against the knowledge_gateway database.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS public.users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(100) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    department    VARCHAR(100) NOT NULL,
    role          VARCHAR(50) NOT NULL,
    token         TEXT NOT NULL UNIQUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- psql prompts for each password; passwords are hashed before storage.
\prompt 'Demo password for alice (engineering employee): ' alice_password
INSERT INTO public.users (username, password_hash, department, role, token)
VALUES ('alice', crypt(:'alice_password', gen_salt('bf')), 'engineering', 'employee', encode(gen_random_bytes(32), 'hex'))
ON CONFLICT (username) DO UPDATE SET password_hash = EXCLUDED.password_hash,
    department = EXCLUDED.department, role = EXCLUDED.role, token = EXCLUDED.token;
\unset alice_password

